def gen_template(pool: dict, cat: int) -> tuple[str, str, str]:
    """用模板批量生成一条新闻 (title, description, content)"""
    home, away = random.sample(pool["teams"], 2)
    player = random.choice(pool["players"])
    player2 = random.choice(pool["players"])
    while player2 == player:
        player2 = random.choice(pool["players"])
    score = random.choice(["3-1", "2-0", "2-1", "1-0", "3-0", "4-1"])
    event = random.choice(["梅开二度", "传射建功", "破门制胜", "世界波破门", "绝杀救主", "帽子戏法"])
    league = CAT_NAMES[cat]

    mins = sorted(random.sample([15, 23, 28, 35, 41, 48, 52, 58, 63, 67, 72, 78, 83, 88], 3))
    m1, m2, m3 = mins
    poss = random.randint(48, 68)
    shots = random.randint(10, 22)
    quote = random.choice(QUOTES)
    opponent = random.choice(pool["teams"])
    while opponent in (home, away):
        opponent = random.choice(pool["teams"])

    title = f"{home}{score}{away} {player}{event}"
    desc = f"{home}在{league}焦点战中{score}击败{away}，{player}表现抢眼。"
    content = (
        f"本场{league}焦点战，{home}坐镇主场迎战{away}。第{m1}分钟，{player}帮助{home}首开纪录；"
        f"第{m2}分钟，{away}由{player2}扳平比分。双方上半场互有攻守。\n\n"
        f"易边再战，{home}加强攻势，第{m3}分钟{player}再度建功，将比分锁定为{score}。"
        f"此后{away}虽奋力反扑，但未能改写比分。\n\n"
        f"赛后统计显示，{home}控球率{poss}%，射门{shots}次，占据明显优势。主帅赛后表示：\"{quote}\"。"
        f"此役过后，{home}在{league}积分榜上排名上升。\n\n"
        f"下一轮，{home}将客场对阵{opponent}，球队上下目标延续良好势头。"
    )
    return title, desc, content


async def seed() -> None:
    async with AsyncSessionLocal() as db:
        # 1. 清空旧数据（先清子表，再清 news，保证可重复执行）
        await db.execute(RelatedNews.__table__.delete())
        await db.execute(Favorite.__table__.delete())
        await db.execute(History.__table__.delete())
        await db.execute(News.__table__.delete())

        # 2. 组装记录：按 pos 0..19 逐类生成，保证发布时间全局交错（推荐频道天然混合各分类）
        records: list[News] = []
        idx = 0
        for pos in range(PER_CATEGORY):
            for cat in range(1, CATEGORY_COUNT + 1):
                pool = POOLS[cat]
                if pos < len(HANDPICKED.get(cat, [])):
                    title, desc, content = HANDPICKED[cat][pos]
                else:
                    title, desc, content = gen_template(pool, cat)
                records.append(
                    News(
                        title=title,
                        description=desc,
                        content=content,
                        image=f"https://picsum.photos/seed/football{idx + 1}/400/300",
                        author=AUTHORS[idx % len(AUTHORS)],
                        category_id=cat,
                        views=random.randint(3000, 30000),
                        publish_time=BASE_TIME - timedelta(hours=idx * 3 + random.randint(0, 2)),
                    )
                )
                idx += 1

        # 3. 批量入库
        db.add_all(records)
        await db.commit()
        print(f"已生成 {len(records)} 条足球新闻（8 分类 × {PER_CATEGORY} 条）")


async def main() -> None:
    await seed()
    # 释放连接池，避免退出时的清理告警
    await engine.dispose()


